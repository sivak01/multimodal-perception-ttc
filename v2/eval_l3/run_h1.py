"""
v2/eval_l3/run_h1.py — H1 (refined) entry point.

Run with: python -m v2.eval_l3.run_h1
Writes output/eval_l3/fused_enriched_keys.csv (the per-key dataset) and
output/eval_l3/h1_refined_verdict.md (the required results table +
plain-English verdict + exact numbers + limitations, per rule 8). Does
not touch repo root or any v1/v2 file outside v2/eval_l3/.
"""
import time
from pathlib import Path

from v2.eval_l3 import config_l3 as cfg
from v2.eval_l3 import stratify
from v2.eval_l3.build_fused_dataset import build, write_csv
from v2.eval_l3.hypothesis_h1 import compare_merged_vs_single, verdict_for

OUT_DIR = Path("output/eval_l3")
BOUNDS = ("hungarian", "lock_once")
BOUND_LABEL = {"hungarian": "per-frame Hungarian (optimistic)", "lock_once": "lock-once (pessimistic)"}

SLICES = [
    ("a_all_qualifying_groups", "Part (a): same instance + range bucket, no further restriction", None),
    ("b_corridor_only", "Part (b): same instance + range bucket, in-corridor only (|lateral|<=%.1fm, 0<=forward<=%sm)"
     % (cfg.CORRIDOR_HALF_WIDTH_M, cfg.CORRIDOR_MAX_RANGE_M), lambda r: r.in_corridor is True),
    ("b_ttc_band_0_5s", "Part (b): same instance + range bucket, GT TTC in [%s, %s)s only"
     % (cfg.H1_TTC_BAND_LOW_S, cfg.H1_TTC_BAND_HIGH_S), lambda r: stratify.in_h1_ttc_band(r.gt_ttc)),
]

SUPPLEMENTARY_STRATIFIERS = [
    ("odd", lambda r: r.odd),
    ("class_group", lambda r: r.class_group),
    ("motion", lambda r: r.motion),
    ("range_bucket", lambda r: stratify.range_bucket_label(r.range_bucket)),
]


def _fmt_metric(m):
    return (f"merged={m['merged']} single={m['single']} diff={m['diff_merged_minus_single']} "
            f"95%CI=[{m['ci95_low']}, {m['ci95_high']}]")


def run():
    print("Building enriched fused-run dataset (lidar/radar/camera_mono/fused trackers, both matching bounds)...")
    t0 = time.time()
    rows = build()
    print(f"  done in {time.time() - t0:.1f}s")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    write_csv(rows, OUT_DIR / "fused_enriched_keys.csv")
    print(f"  wrote {OUT_DIR / 'fused_enriched_keys.csv'} ({len(rows)} rows)")

    lines = []
    lines.append("# H1 (refined): does merged (2+ sensor) fused output beat single-sensor,")
    lines.append("# matched on the SAME GT instance + range bucket?\n")
    lines.append(f"Generated by `python -m v2.eval_l3.run_h1`. {len(rows)} total enriched rows "
                  f"({sum(1 for r in rows if r.bound=='hungarian')} hungarian + "
                  f"{sum(1 for r in rows if r.bound=='lock_once')} lock_once).\n")
    lines.append("Pass/fail rule (given verbatim): **CONFIRMED** if merged beats single within the "
                  "same instance+range bucket and the 95% CI of the difference excludes 0. "
                  "**REFUTED** if the CI includes 0 or favours single. **INCONCLUSIVE** (added per "
                  f"this session's rule 4) if fewer than {cfg.MIN_N_FOR_RELIABLE_CI} qualifying "
                  "(instance, range_bucket) groups exist.\n")

    all_results = {}
    for bound in BOUNDS:
        lines.append(f"\n## Matching bound: {BOUND_LABEL[bound]}\n")
        for slice_key, slice_label, restrict_fn in SLICES:
            result = compare_merged_vs_single(rows, bound, restrict_fn)
            verdict, reason = verdict_for(result)
            all_results[(bound, slice_key)] = (result, verdict, reason)

            lines.append(f"### {slice_label}\n")
            lines.append(f"- n qualifying (instance, range_bucket) groups: **{result['n_qualifying_groups']}**"
                          + (f"  (< {cfg.MIN_N_FOR_RELIABLE_CI} -- flagged, see INCONCLUSIVE below)"
                             if result['n_qualifying_groups'] < cfg.MIN_N_FOR_RELIABLE_CI else ""))
            lines.append(f"- n merged rows: {result['n_merged_rows']}, n single rows: {result['n_single_rows']}")
            for metric_name in ("mae", "median", "p90", "rel_mae"):
                m = result["metrics"][metric_name]
                lines.append(f"- **{metric_name}**: {_fmt_metric(m)}")
            st = result["paired_sign_test"]
            lines.append(f"- paired sign test (per group, single_error - merged_error; positive = merged better): "
                          f"n={st['n']} merged_better={st['n_positive']} single_better={st['n_negative']} "
                          f"ties={st['n_ties']} p_value={st['p_value']}")
            lines.append(f"- **VERDICT: {verdict}** -- {reason}\n")

            print(f"[{bound}] {slice_label}: n_groups={result['n_qualifying_groups']} "
                  f"MAE diff={result['metrics']['mae']['diff_merged_minus_single']} -> {verdict}")

    lines.append("\n## Supplementary stratification (rule 6), part (a) population only, MAE only\n")
    lines.append("Not part of H1's own (a)/(b)/(c) pass/fail rule -- reported for rule 6's general "
                  "\"stratify every headline metric\" requirement. Same instance+range-bucket pairing "
                  "as part (a), additionally sliced by one stratifier at a time (not cross-combined, to "
                  "keep each slice's n interpretable).\n")
    for bound in BOUNDS:
        lines.append(f"\n### {BOUND_LABEL[bound]}\n")
        for strat_name, key_fn in SUPPLEMENTARY_STRATIFIERS:
            lines.append(f"\n**By {strat_name}:**\n")
            values = sorted({key_fn(r) for r in rows if r.bound == bound and key_fn(r) is not None})
            for v in values:
                result = compare_merged_vs_single(rows, bound, restrict_fn=lambda r, v=v, key_fn=key_fn: key_fn(r) == v)
                verdict, _reason = verdict_for(result)
                mae = result["metrics"]["mae"]
                lines.append(f"- `{strat_name}={v}`: n_groups={result['n_qualifying_groups']} "
                              f"MAE merged={mae['merged']} single={mae['single']} "
                              f"diff={mae['diff_merged_minus_single']} CI=[{mae['ci95_low']}, {mae['ci95_high']}] "
                              f"-> {verdict}")

    lines.append("\n## Limitations\n")
    lines.append("- Composition (\"merged\" vs \"single\") is derived INDEPENDENTLY of the fused "
                  "tracker's own `is_multi_sensor` bookkeeping: it counts how many of the three solo "
                  "single-sensor trackers (lidar/radar/camera_mono, same CentralTracker class, run "
                  "separately) had a candidate within MATCH_DIST_THRESHOLD_M of the real object at that "
                  "exact sample. This avoids the whole-track-lifetime forward-looking bias a track-level "
                  "flag would introduce (a track that becomes multi-sensor LATER would otherwise be "
                  "labelled \"merged\" even at an earlier, still-single-sensor instant).")
    lines.append("- The in-corridor check uses ego's own BODY heading (yaw, from each sample's real "
                  "ego_pose rotation quaternion), not its velocity heading -- see ego_heading.py.")
    lines.append("- class_group/odd/motion can be undefined for a given row (e.g. a GT instance whose "
                  "category or speed could not be resolved); such rows are excluded from the relevant "
                  "supplementary stratification slice only, not from the main (a)/(b)/(c) analyses.")
    lines.append("- All thresholds (config_l3.py) are ASSUMED, fixed before any result was computed, "
                  "and were not tuned after seeing these numbers.")
    lines.append(f"- Scene-level bootstrap: {cfg.BOOTSTRAP_N_RESAMPLES} resamples, seed {cfg.BOOTSTRAP_SEED}, "
                  f"{cfg.BOOTSTRAP_CI_PCT}% CI, resampling the (up to 10) real scenes with replacement -- "
                  "not individual rows -- per this session's own rule 4.")

    verdict_path = OUT_DIR / "h1_refined_verdict.md"
    verdict_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {verdict_path}")
    return all_results


if __name__ == "__main__":
    run()
